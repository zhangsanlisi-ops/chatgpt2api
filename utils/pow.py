"""Current Sentinel resource parsing and FNV-1a/avalanche verification.

The live 25-field requirements fingerprint and proof are generated by the
private Chromium solver using the current first-party Sentinel SDK. This
module intentionally contains no legacy SHA3 or simulated browser fingerprint.
"""
from __future__ import annotations

import base64
import re
from html.parser import HTMLParser

DEFAULT_POW_SCRIPT = "https://chatgpt.com/backend-api/sentinel/sdk.js"


class ScriptSrcParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.script_sources: list[str] = []
        self.data_build = ""

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag != "script":
            return
        src = dict(attrs).get("src")
        if not src:
            return
        self.script_sources.append(src)
        match = re.search(r"c/[^/]*/_", src)
        if match:
            self.data_build = match.group(0)


def parse_pow_resources(html_content: str) -> tuple[list[str], str]:
    parser = ScriptSrcParser()
    parser.feed(html_content)
    sources = parser.script_sources or [DEFAULT_POW_SCRIPT]
    data_build = parser.data_build
    if not data_build:
        match = re.search(r'<html[^>]*data-build="([^"]*)"', html_content)
        if match:
            data_build = match.group(1)
    return sources, data_build


def fnv1a_avalanche_32(text: str) -> str:
    """Match SDK Math.imul/charCodeAt 32-bit hashing, including UTF-16 units."""
    h = 0x811C9DC5
    utf16 = text.encode("utf-16-le", "surrogatepass")
    for i in range(0, len(utf16), 2):
        unit = utf16[i] | (utf16[i + 1] << 8)
        h = ((h ^ unit) * 0x01000193) & 0xFFFFFFFF
    h ^= h >> 16
    h = (h * 0x85EBCA6B) & 0xFFFFFFFF
    h ^= h >> 13
    h = (h * 0xC2B2AE35) & 0xFFFFFFFF
    h ^= h >> 16
    return f"{h:08x}"


def verify_proof_token(seed: str, difficulty: str, proof_token: str) -> bool:
    if not proof_token.startswith("gAAAAAB") or not proof_token.endswith("~S"):
        return False
    encoded = proof_token[len("gAAAAAB"):-2]
    try:
        base64.b64decode(encoded, validate=True)
    except (ValueError, base64.binascii.Error):
        return False
    return fnv1a_avalanche_32(seed + encoded)[:len(difficulty)] <= difficulty.lower()
